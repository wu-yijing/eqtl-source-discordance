def sha256(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, 'rb') as fh:
        for block in iter(lambda: fh.read(chunk), b''):
            h.update(block)
    return h.hexdigest()


def tracked_files():
    """`git ls-files`, as repository-relative POSIX paths, sorted."""
    out = subprocess.run(['git', 'ls-files', '-z'], cwd=REPO,
                         stdout=subprocess.PIPE, check=True).stdout
    return sorted(p.decode('utf-8') for p in out.split(b'\0') if p)


def index_blobs():
    """`path -> content bytes`, taken from the INDEX, not the working tree.

    WHY THE INDEX. Hashing the working tree records bytes that depend on the
    platform: a Windows checkout of a `eol=lf` file can differ from a Linux one,
    and any script that writes a log or a CSV with Python's default text mode puts
    CRLF back. Both make the manifest verify on the machine that produced it and
    fail for a reader who cloned — which is the opposite of the point. The index
    content IS what a fresh clone receives, so that is what gets hashed.

    Returns (blobs, missing) where `blobs` maps path -> bytes and `missing` lists
    paths whose object is not in the store.
    """
    raw = subprocess.run(['git', 'ls-files', '-s', '-z'], cwd=REPO,
                         stdout=subprocess.PIPE, check=True).stdout
    sha_by_path = {}
    for rec in raw.split(b'\0'):
        if not rec:
            continue
        meta, _, path = rec.partition(b'\t')
        parts = meta.split()
        if len(parts) >= 2:
            sha_by_path[path.decode('utf-8')] = parts[1].decode('ascii')

    sha_list = sorted(set(sha_by_path.values()))
    feed = b''.join(s.encode('ascii') + b'\n' for s in sha_list)
    out = subprocess.run(['git', 'cat-file', '--batch'], cwd=REPO, input=feed,
                         stdout=subprocess.PIPE, check=True).stdout

    blobs, pos, missing = {}, 0, []
    for sha in sha_list:
        nl = out.find(b'\n', pos)
        header = out[pos:nl].split()
        if len(header) < 3 or header[1] != b'blob':
            missing.append(sha)
            pos = nl + 1
            continue
        size = int(header[2])
        blobs[sha] = out[nl + 1: nl + 1 + size]
        pos = nl + 1 + size + 1                    # skip the trailing newline
    by_path = {p: blobs.get(s) for p, s in sha_by_path.items()}
    return by_path, set(missing)


def _env_versions():
    """Version string for `generated_by.analysis_env`, read from the shipped pins.

    These used to be a free-text literal that said "Python 3.13.0" while
    `env/environment.yml` pinned 3.13.12 — the manifest disagreed with the
    environment it claimed to describe, and nothing caught it because no gate
    reads that field. Deriving the string from the pin files makes the two
    impossible to disagree. Falls back to the literal only if a pin cannot be
    parsed, and says so rather than guessing.
    """
    py = r = None
    try:
        with open(os.path.join(REPO, 'env', 'environment.yml'), encoding='utf-8') as f:
            m = re.search(r'^\s*-\s*python\s*=\s*([0-9][0-9.]*)', f.read(), re.M)
            if m:
                py = m.group(1)
    except OSError:
        pass
    try:
        with open(os.path.join(REPO, 'env', 'renv.lock'), encoding='utf-8') as f:
            m = re.search(r'"R"\s*:\s*\{\s*"Version"\s*:\s*"([0-9][0-9.]*)"', f.read())
            if m:
                r = m.group(1)
    except OSError:
        pass
    if not (py and r):
        return ('Python 3.13.12 / R 4.5.2 with MatchIt, pinned as env/environment.yml and '
                'env/renv.lock (version strings could not be read from the pins)')
    return ('Python %s / R %s with MatchIt, pinned as env/environment.yml and env/renv.lock'
            % (py, r))


def main():
    excluded_paths = {p for p, _ in EXCLUDED}
    blobs, missing = index_blobs()
    files, skipped = [], []
    for rel in tracked_files():
        if rel in excluded_paths:
            continue
        content = blobs.get(rel)
        if content is None:
            skipped.append({'path': rel,
                            'reason': 'staged object not readable as a blob%s'
                                      % (' (object missing)' if missing else '')})
            continue
        files.append({'path': rel, 'bytes': len(content),
                      'sha256': hashlib.sha256(content).hexdigest()})
    files.sort(key=lambda x: x['path'])

    excluded = [{'path': p, 'reason': r} for p, r in EXCLUDED]
    excluded += skipped
    tracked_count = len(tracked_files())

    external = []
    for row in EXTERNAL:
        artefacts = row.get("files", [])
        held = [f for f in artefacts if f.get("sha256")]
        retrieved, basis = EXTERNAL_RETRIEVAL.get(row["id"], ("unknown", "not recorded"))
        entry = {
            "id": row["id"], "role": row["role"], "version": row["version"],
            "source_url": row["source_url"],
            "retrieved": retrieved,
            "retrieved_basis": basis,
            "retrieval_note": RETRIEVAL_CAVEAT,
            "sha256": (held[0]["sha256"] if len(held) == 1 else
                       ("held — %d artefacts, see 'files'" % len(held) if held else "not-held")),
            "sha256_note": ("Hash of the copy that produced the reported numbers. Recorded 2026-10-03, "
                            "and re-verified by re-running the upstream stage against it "
                            "(code/run_upstream.sh). Check a download with "
                            "scripts/verify_external_inputs.py."),
            "files": artefacts,
        }
        if row.get("citation"):
            entry["citation"] = row["citation"]
        external.append(entry)

    doc = {
        "_note": ("Provenance manifest. Regenerate with scripts/collect_provenance.py before each "
                  "release. 'external_inputs' is documentation; 'files' hashes every file tracked "
                  "by git, apart from the declared 'excluded' entries. "
                  "scripts/cut_release.sh asserts len(files) + len(excluded) == git ls-files."),
        "schema_version": "3.0",
        "generated_by": {
            "script": "scripts/collect_provenance.py",
            "python": sys.version.split()[0],
            "platform": platform.platform(),
            "metaxcan": "MetaXcan v0.8.1 (official binary)",
            "analysis_env": _env_versions(),
        },
        "external_inputs": external,
        "repro_inputs": REPRO_INPUTS,
        "repro_inputs_note": ("Inputs of code/analyses/reproduction_20261002/ that are NOT "
                              "redistributed with this archive. Hashes were measured on the machine "
                              "that produced that package's results/. Shipped inputs are covered by "
                              "'files' above; the full manifest is "
                              "code/analyses/reproduction_20261002/INPUTS.md."),
        "external_input_caveat": ANCESTRY_NOTE,
        "files": files,
        "file_count": len(files),
        "excluded": excluded,
        "tracked_file_count": tracked_count,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(doc, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    print('wrote %s' % OUT)
    print('  tracked %d, hashed %d, excluded %d, external inputs %d, reproduction inputs %d'
          % (tracked_count, len(files), len(excluded), len(external), len(REPRO_INPUTS)))
    if len(files) + len(excluded) != tracked_count:
        print('  !! COVERAGE MISMATCH — cut_release.sh will refuse the release')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
