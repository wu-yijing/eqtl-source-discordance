"""Regenerate metadata/provenance.json.

Hashes **every file tracked by git** and records the external-input manifest.
Run before each release; `scripts/cut_release.sh` fails the release if the
manifest does not cover the tree.

    python scripts/collect_provenance.py

WHY EVERY TRACKED FILE, NOT A HAND-PICKED LIST
----------------------------------------------
The first version hashed three directories (`data/derived`, `code/analyses/recovered`,
`code/figures`) and registered 36 files against a tree of 281. Nothing forced the two
numbers to agree, so the 59-file reproduction package added on 2026-10-02 was
registered **zero** times, and the top-level README's claim that *"every input file is
pinned by checksum in metadata/provenance.json"* was false for every one of its
eight external inputs. The coverage gate in `cut_release.sh` now makes that
impossible: manifest entries + declared exclusions must equal `git ls-files`.

The hashes are taken from the **index** — i.e. from the bytes a fresh clone receives —
not from the working tree. Hashing the working tree made the manifest verify on the
machine that produced it and fail anywhere the line endings differed; `index_blobs()`
records what a reader actually gets.

The only exclusion is the manifest itself, which cannot hash itself.

The external-input half is documentation, not discovery: those resources are still
not redistributed here, but their hashes are now **held** — 2026-10-03, the copies
that produced the reported numbers were hashed on disk and the upstream stage was
re-run against them (code/run_upstream.sh), so the `sha256` fields record a
verified identity rather than `not-held`. Identifiers, versions and the retrieval
date come from Supporting Information Note S4.
"""
