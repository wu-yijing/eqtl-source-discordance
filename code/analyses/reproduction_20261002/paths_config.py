def open_text(path, encoding='utf-8-sig'):
    """Open plain or gzip-compressed text transparently."""
    if str(path).endswith('.gz'):
        return io.TextIOWrapper(gzip.open(path, 'rb'), encoding=encoding, newline='')
    return open(path, encoding=encoding, newline='')


def rows(path):
    """list[list[str]] for a CSV/TSV, gzip-aware."""
    with open_text(path) as f:
        return list(csv.reader(f))


def dict_rows(path):
    with open_text(path) as f:
        return list(csv.DictReader(f))


def md5(path):
    h = hashlib.md5()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def content_md5(path):
    """MD5 of the *decompressed* bytes for a `.gz` file, of the raw bytes otherwise.

    Five inputs ship gzipped to keep the repository small. Hashing the compressed
    bytes would make an input's recorded hash depend on the compressor, so the
    scripts record this instead and the numbers stay comparable with the run that
    produced the published values.
    """
    if str(path).endswith('.gz'):
        h = hashlib.md5()
        with gzip.open(path, 'rb') as f:
            for chunk in iter(lambda: f.read(1 << 20), b''):
                h.update(chunk)
        return h.hexdigest()
    return md5(path)


def describe_inputs(paths):
    """`{name: {'md5', 'bytes', 'content_md5'}}` for a mapping of name -> path."""
    out = {}
    for name, p in paths.items():
        rec = {'md5': md5(p), 'bytes': os.path.getsize(p)}
        if str(p).endswith('.gz'):
            rec['content_md5'] = content_md5(p)
        out[name] = rec
    return out


def check_shipped():
    """Assert every shipped input is present and, where recorded, byte-exact."""
    bad = []
    for name, (p, h, sz) in SHIPPED.items():
        if not os.path.exists(p):
            bad.append((name, 'MISSING', p))
            continue
        if os.path.isdir(p):
            continue
        if h and md5(p) != h:
            bad.append((name, 'MD5 MISMATCH', p))
        elif sz and os.path.getsize(p) != sz:
            bad.append((name, 'SIZE MISMATCH', p))
    return bad


