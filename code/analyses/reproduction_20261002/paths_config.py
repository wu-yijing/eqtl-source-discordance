class MissingInput(SystemExit):
    """Raised with an actionable message rather than a traceback."""

    def __init__(self, what, path, how):
        super().__init__(
            '\n[missing input] %s\n'
            '  looked for : %s\n'
            '  expected   : %s\n'
            '  how to get : %s\n'
            '  override   : set the environment variable named above, or pass the\n'
            '               corresponding command-line flag (see --help).\n' % (
                what, path, _EXPECT.get(what, 'see INPUTS.md'), how))


_EXPECT = {}


def need(logical_or_path, what=None, how=None):
    """Resolve and existence-check, printing an actionable message."""
    p = get(logical_or_path) if logical_or_path in SHIPPED or logical_or_path in DOCS else logical_or_path
    if not os.path.exists(p):
        raise MissingInput(what or logical_or_path, p, how or 'see INPUTS.md')
    return p


def get(logical):
    """Path for a shipped input or a submission document."""
    if logical in SHIPPED:
        return SHIPPED[logical][0]
    if logical in DOCS:
        d = DOCS[logical]
        p = os.environ.get(d['env']) or d['default']
        return p
    raise KeyError('unknown logical input: %r' % logical)


def doc(logical):
    """Resolve a submission document, with a message naming the file to supply."""
    d = DOCS[logical]
    p = os.environ.get(d['env']) or d['default']
    if not os.path.exists(p):
        exp = d['expect']
        hint = ('%s; the file distributed with the submission is named "%s"'
                % (d['what'], exp)) if exp else d['what']
        if d['md5']:
            hint += ' (md5 %s, %s bytes)' % (d['md5'], format(d['bytes'], ','))
        raise MissingInput(logical, p, hint + '. Set %s=/path/to/%s' % (d['env'], exp or 'file'))
    return p


def external_dir(logical):
    """Resolve a non-redistributed bulk directory (mashr models, raw MetaXcan runs)."""
    d = EXTERNAL_DIRS[logical]
    root = os.environ.get(d['env']) or d['default']
    if not root or not os.path.isdir(root):
        lines = ['  files needed:']
        for fn, (h, sz) in d['files'].items():
            lines.append('    %-38s md5=%s bytes=%s' % (fn, h, sz))
        raise MissingInput(logical, root or ('$%s (unset)' % d['env']),
                           '%s. Not redistributed — see INPUTS.md for the acquiry route.\n%s'
                           % (d['what'], '\n'.join(lines)))
    return root


