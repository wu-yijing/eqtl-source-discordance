def _find_repo(start):
    """Walk up from `start` looking for the repository sentinel."""
    d = start
    for _ in range(8):
        if os.path.exists(os.path.join(d, _SENTINEL)):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    # Historical layout fallback: <repo>/code/analyses/reproduction_20261002/
    return os.path.dirname(os.path.dirname(os.path.dirname(start)))


