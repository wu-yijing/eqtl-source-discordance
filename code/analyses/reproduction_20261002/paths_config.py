"""Reproduction package — the single path entry point.

`code/README.md` rule 3: *"No absolute paths, no personal directories. All paths
resolve from a single `paths_config.py` (or equivalent) at the repository root."*
Every script in this directory reads its input paths from here.

The contract mirrors `code/figures/paths_config.py`, so a reader who has already
configured one package has configured both:

| environment variable | meaning | default |
|---|---|---|
| `TWAS_REPO` | repository root (the directory holding `.zenodo.json`) | first ancestor with `.zenodo.json` |
| `TWAS_DATA_Z` | authoritative Z data layer | `<TWAS_REPO>/data/derived` |
| `REPRO_MS_DOCX` | the submitted manuscript `.docx` | `<TWAS_REPO>/manuscript/Manuscript.docx` |
| `REPRO_SI_DOCX` | the submitted Supporting Information `.docx` | `<TWAS_REPO>/manuscript/Supporting_Information.docx` |
| `REPRO_AF1_DOCX` | "Additional file 1", the review-revision SI that `m15_pc.py` patches | `<TWAS_REPO>/manuscript/Additional_file_1.docx` |
| `REPRO_MASHR_DB_DIR` | mashr eQTL model databases (third-party; not redistributed) | unset |
| `REPRO_GTEX_OFFICIAL_DIR` | the six official MetaXcan GTEx x FinnGen tables (not redistributed) | unset — the shipped wide table is used instead |

Three document classes are deliberately **not** tracked in this repository:
the submitted manuscripts, and the mashr model databases. Their paths therefore
have no working default; `need()` says exactly what to download and where to
point the variable.

Every shipped input is listed in `INPUTS.md` with its MD5 and byte count, and
the same hashes are asserted here. A run either matches them or says so.
"""
