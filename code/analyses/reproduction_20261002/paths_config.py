# Supporting-Information table extraction (replaces pre-extracted .tsv files)
# ---------------------------------------------------------------------------
_W = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'


def _para_text(p):
    out = []
    for n in p.iter():
        if n.tag == _W + 't':
            out.append(n.text or '')
        elif n.tag == _W + 'tab':
            out.append('\t')
        elif n.tag == _W + 'br':
            out.append('\n')
    return ''.join(out)


def si_tables(path=None):
    """Extract every table from the Supporting Information `.docx`.

    Returns a list of dicts: `{'title', 'rows', 'note', 'index'}` where `rows` is a
    rectangular `list[list[str]]` with gridSpan/vMerge expanded so columns align.
    Extracting from the `.docx` directly means the package does not need the
    pre-extracted TSVs that the diagnostic scripts originally read.
    """
    import zipfile
    from xml.etree import ElementTree as ET

    path = path or doc('si')
    z = zipfile.ZipFile(path)
    body = ET.fromstring(z.read('word/document.xml')).find(_W + 'body')
    children = list(body)
    out = []
    for k, c in enumerate(children):
        if c.tag != _W + 'tbl':
            continue
        title = ''
        for j in range(k - 1, -1, -1):
            if children[j].tag == _W + 'p' and _para_text(children[j]).strip():
                title = _para_text(children[j]).strip()
                break
        note = ''
        for j in range(k + 1, len(children)):
            if children[j].tag == _W + 'p' and _para_text(children[j]).strip():
                note = _para_text(children[j]).strip()
                break
        rows = []
        for tr in c.findall(_W + 'tr'):
            row = []
            for tc in tr.findall(_W + 'tc'):
                txt = '\n'.join(_para_text(p) for p in tc.findall(_W + 'p')).strip()
                span = 1
                pr = tc.find(_W + 'tcPr')
                if pr is not None:
                    gs = pr.find(_W + 'gridSpan')
                    if gs is not None:
                        span = int(gs.get(_W + 'val'))
                    vm = pr.find(_W + 'vMerge')
                    if vm is not None and (vm.get(_W + 'val') or 'continue') == 'continue':
                        txt = ''
                row.append(txt)
                row.extend(['<span>'] * (span - 1))
            rows.append(row)
        width = max((len(r) for r in rows), default=0)
        for r in rows:
            r.extend([''] * (width - len(r)))
        out.append({'index': len(out), 'title': title, 'note': note, 'rows': rows})
    return out


def si_table_by_address(address, path=None):
    """Fetch `Table S13` (or `S4a`) from the Supporting Information by its label."""
    m = re.match(r'\s*S?(\d+[a-z]?)\s*$', address.strip(), re.I)
    if not m:
        raise ValueError('not a table address: %r' % address)
    want = m.group(1).lower()
    for t in si_tables(path):
        lab = re.match(r'\s*Table\s*S?(\d+[a-z]?)', t['title'], re.I)
        if lab and lab.group(1).lower() == want:
            return t
    raise KeyError('Supporting Information has no table %s' % address)


def si_table_rows(address, path=None):
    """Rectangular rows (header at index 0) for `Table S13` and friends."""
    return si_table_by_address(address, path)['rows']


def si_rows_by_object(i, path=None):
    """Rows for table *object* `i`, i.e. the order the tables appear in the docx.

    The submitted Supporting Information places `Table S1` at object 0; because
    S5 is split into S5a and S5b the mapping `object i = Table S(i+1)` holds for
    the whole document (31 objects, S1-S30).
    """
    return si_tables(path)[i]['rows']


def report():
    print('  %-22s = %s' % ('REPO', REPO))
    for k in ('DERIVED', 'GENOMEWIDE', 'SUPERSEDED', 'RESULTS', 'LOGS', 'FORBIDDEN'):
        print('  %-22s = %s' % (k, globals()[k]))
    print()
    print('  shipped inputs:')
    for name, (p, h, sz) in SHIPPED.items():
        mark = 'ok ' if os.path.exists(p) else 'MISSING'
        print('    [%s] %-20s %s' % (mark, name, p))
    print()
    print('  submission documents (not redistributed):')
    for k, d in DOCS.items():
        p = os.environ.get(d['env']) or d['default']
        mark = 'ok ' if os.path.exists(p) else 'not supplied'
        print('    [%-12s] %-12s %s' % (mark, k, p))
    bad = check_shipped()
    print()
    print('  self-check: %s' % ('all shipped inputs present and byte-exact'
                                if not bad else '%d problem(s): %s' % (len(bad), bad)))
    return bad


def cli_path(name, default=None):
    """Read `--<name> PATH` from argv (also `--<name>=PATH`), falling back to a default."""
    flag = '--' + name.replace('_', '-')
    argv = sys.argv[1:]
    for i, a in enumerate(argv):
        if a == flag and i + 1 < len(argv):
            return argv[i + 1]
        if a.startswith(flag + '='):
            return a.split('=', 1)[1]
    return default


def apply_cli_overrides():
    """Map `--repo-root`, `--ms-docx`, `--si-docx`, `--af1-docx`, `--mashr-db-dir`
    and `--gtex-official-dir` onto the corresponding environment variables, then
    recompute the derived constants. Call once, first thing, from a script body."""
    pairs = [('repo_root', _ENV_REPO), ('ms_docx', DOCS['manuscript']['env']),
             ('si_docx', DOCS['si']['env']), ('af1_docx', DOCS['af1']['env']),
             ('mashr_db_dir', EXTERNAL_DIRS['mashr_db_dir']['env']),
             ('gtex_official_dir', EXTERNAL_DIRS['gtex_official_dir']['env'])]
    for flag, env in pairs:
        v = cli_path(flag)
        if v:
            os.environ[env] = v
    reload_paths()


def reload_paths():
    """Recompute every module-level path from the current environment."""
    global REPO, DERIVED, GENOMEWIDE, SUPERSEDED, SHIPPED, FORBIDDEN
    REPO = os.environ.get(_ENV_REPO) or _find_repo(HERE)
    DERIVED = os.environ.get('TWAS_DATA_Z') or os.path.join(REPO, 'data', 'derived')
    GENOMEWIDE = os.path.join(DERIVED, 'genomewide')
    SUPERSEDED = os.path.join(REPO, 'data', 'superseded')
    FORBIDDEN = SUPERSEDED
    SHIPPED = _build_shipped()
    for _k, _d in DOCS.items():
        _d['default'] = os.path.join(REPO, 'manuscript', os.path.basename(_d['default']))


for _k, _d in DOCS.items():
    _EXPECT[_k] = _d['what']

if __name__ == '__main__':
    apply_cli_overrides()
    # Non-zero exit on a mismatch. The first version only printed the verdict, so a
